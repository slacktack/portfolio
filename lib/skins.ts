export const defaultSkin: SkinId = "paper";

export const getSkin = (id: string | undefined | null) => skins.find((s) => s.id === id) ?? skins[0];

const bootList = skins.filter((s) => s.ready).map((s) => [s.id, s.mode, s.app ? 1 : 0]);

// Runs before paint: ?skin= wins, then the stored skin, then the old day/night key.
// data-exp hides Paper's markup while a full theme app loads; data-first opens the picker.
export const skinBootScript = `(function(){var m={},a={};${JSON.stringify(bootList)}.forEach(function(p){m[p[0]]=p[1];a[p[0]]=p[2]});var d=document.documentElement;try{var q=new URLSearchParams(location.search).get("skin");var st=localStorage.getItem("tg-skin");var s=m[q]?q:st;if(!m[s]){s=localStorage.getItem("tg-theme")==="night"?"night":"paper"}if(m[q])localStorage.setItem("tg-skin",q);if(!m[q]&&!localStorage.getItem("tg-picked"))d.dataset.first="1";d.dataset.skin=s;d.dataset.theme=m[s];if(a[s])d.dataset.exp="1"}catch(e){d.dataset.skin="paper";d.dataset.theme="day"}})();`;
